/** Keep existing compatibility codecs; all wire numbers are strings, including nested snapshots. */
object SyncJson {
    fun numericStrings(value: Any?): Any? = when (value) {
        is JSONObject -> JSONObject().also { result -> value.keys().forEach { result.put(it, numericStrings(value.get(it))) } }
        is JSONArray -> JSONArray().also { result -> (0 until value.length()).forEach { result.put(numericStrings(value.get(it))) } }
        is BigDecimal -> value.toPlainString()
        is Double -> { require(value.isFinite()); BigDecimal.valueOf(value).toPlainString() }
        is Float -> { require(value.isFinite()); BigDecimal(value.toString()).toPlainString() }
        is Number -> value.toString()
        is String -> {
            if (value.isNotEmpty() && (value.contains('e') || value.contains('E')) && (value.first().isDigit() || value.first() == '-')) {
                runCatching { BigDecimal(value).toPlainString() }.getOrDefault(value)
            } else value
        }
        else -> value
    }
    fun record(value: Any): JSONObject {
        val json = when (value) {
            is Customer -> PersistenceJsonCodecs.encodeCustomers(listOf(value))
            is LedgerTransaction -> PersistenceJsonCodecs.encodeLedgerTransactions(listOf(value))
            is BarterInvoice -> PersistenceJsonCodecs.encodeBarterInvoices(listOf(value))
            is Invoice -> PersistenceJsonCodecs.encodeInvoices(listOf(value))
            is InventoryItem -> PersistenceJsonCodecs.encodeInventoryItems(listOf(value))
            is StockAdjustment -> PersistenceJsonCodecs.encodeStockAdjustments(listOf(value))
            is PortfolioItem -> PersistenceJsonCodecs.encodePortfolioItems(listOf(value))
            else -> error("Unsupported record")
        }
        return numericStrings(JSONArray(json).getJSONObject(0)) as JSONObject
    }
    fun business(s: AppSettings): JSONObject = JSONObject().put("id", "business")
        .put("galleryName", s.galleryName).put("managerName", s.managerName).put("unionCode", s.unionCode)
        .put("galleryPhone", s.galleryPhone).put("galleryAddress", s.galleryAddress).put("galleryLicense", s.galleryLicense)
        .put("defaultProfitPercent", s.defaultProfitPercent).put("defaultTaxPercent", s.defaultTaxPercent)
        .put("defaultWageType", s.defaultWageType.name).put("priceSource", s.priceSource.name).put("autoSyncRates", s.autoSyncRates)
    fun applyBusiness(s: AppSettings, j: JSONObject): AppSettings = s.copy(
        galleryName=j.getString("galleryName"), managerName=j.getString("managerName"), unionCode=j.getString("unionCode"),
        galleryPhone=j.getString("galleryPhone"), galleryAddress=j.getString("galleryAddress"), galleryLicense=j.getString("galleryLicense"),
        defaultProfitPercent=j.getString("defaultProfitPercent"), defaultTaxPercent=j.getString("defaultTaxPercent"),
        defaultWageType=WageType.valueOf(j.getString("defaultWageType")), priceSource=PriceSource.valueOf(j.getString("priceSource")), autoSyncRates=j.getBoolean("autoSyncRates"))
    fun canonical(value: Any?): String = when(value) {
        is JSONObject -> value.keys().asSequence().toList().sorted().joinToString(",", "{", "}") { JSONObject.quote(it) + ":" + canonical(value.get(it)) }
        is JSONArray -> (0 until value.length()).joinToString(",", "[", "]") { canonical(value.get(it)) }
        is String -> JSONObject.quote(value)
        null, JSONObject.NULL -> "null"
        else -> value.toString()
    }
    private val knownFields = mapOf(
