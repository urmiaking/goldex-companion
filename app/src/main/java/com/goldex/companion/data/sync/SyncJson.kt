    fun preserveUnknown(type: String, old: JSONObject?, fresh: JSONObject?): JSONObject? {
        if(fresh==null || old==null) return fresh
        val result=JSONObject(fresh.toString())
        old.keys().forEach { if(it !in knownFields.getValue(type) && !result.has(it)) result.put(it,old.get(it)) }
        return result
    }
    fun diff(old: JSONObject?, fresh: JSONObject?): JSONObject {
        if (fresh == null) return JSONObject().put("action", "delete")
        if (old == null) return JSONObject().put("action", "create").put("fields", fresh)
        val fields = JSONObject(); val remove = JSONArray()
        fresh.keys().forEach { key -> if (!old.has(key) || canonical(old.get(key)) != canonical(fresh.get(key))) fields.put(key, fresh.get(key)) }
        old.keys().forEach { key -> if (!fresh.has(key)) remove.put(key) }
        return JSONObject().put("action", "patch").put("fields", fields).put("remove", remove)
    }
    fun apply(old: JSONObject?, change: JSONObject): JSONObject? {
        if (change.getString("action") == "delete") return null
        val result = if (change.getString("action") == "create") JSONObject() else JSONObject(requireNotNull(old).toString())
        change.optJSONObject("fields")?.let { fields -> fields.keys().forEach { result.put(it, fields.get(it)) } }
        change.optJSONArray("remove")?.let { remove -> (0 until remove.length()).forEach { result.remove(remove.getString(it)) } }
        return result
    }
}
