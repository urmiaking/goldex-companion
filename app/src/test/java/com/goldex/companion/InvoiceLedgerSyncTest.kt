        val retailCustomer = Customer(
            id = "c-retail-1",
            name = "مشتری عادی",
            goldDebtGrams = 0.0,
            cashDebtTomans = 0L,
            role = "مشتری عادی"
        )

        val craftedItem = BarterCalculationUseCases.calculateCraftedItem(
            title = "گردنبند طلا",
            karat = Karat.K18,
