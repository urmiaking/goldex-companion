    @Test
    fun testWholesalerInvoiceSyncGeneratesGoldWeightTransaction() {
        val initialCustomer = Customer(
            id = "c-wholesaler-1",
            name = "حاج قاسم زرگر",
            goldDebtGrams = 0.0,
            cashDebtTomans = 0L,
            role = "بنکدار و کیفی"
        )

        val craftedItem = BarterCalculationUseCases.calculateCraftedItem(
            title = "دستبند کارتیه",
            karat = Karat.K18,
            grossWeight = 25.0,
            stoneWeight = 0.0,
            spotPrice18k = 24_000_000L,
            wageType = WageType.PERCENTAGE,
            wageInput = 10.0,
            profitPercent = 7.0,
            taxPercent = 9.0
        )

        val scrapItem = BarterCalculationUseCases.calculateScrapItem(
            title = "طلای متفرقه",
            baseKarat = 750,
            karatDeficit = 0,
            grossWeight = 5.0,
            stoneWeight = 0.0,
            spotPrice18k = 24_000_000L
        )

        val invoice = BarterInvoice(
            id = "inv-101",
            invoiceNumber = "1403-101",
            customer = initialCustomer,
            customerRole = CustomerRole.WHOLESALER,
            salesItems = listOf(craftedItem), // 25.0g 18k
            receivedItems = listOf(scrapItem), // 5.0g 18k
            syncWithLedger = true
        )

        val result = InvoiceLedgerSyncUseCase.generateLedgerSync(invoice, initialCustomer)

        assertEquals(1, result.transactionsToCreate.size)
        val tx = result.transactionsToCreate.single()

        assertEquals("inv-101", tx.invoiceId)
        assertEquals("1403-101", tx.invoiceNumber)
        assertTrue(tx.documentNumber.isNotBlank())
        assertFalse(tx.documentNumber.startsWith("IR"))
        assertTrue(tx.isAutoGenerated)
        assertEquals(LedgerEntryType.GOLD_WEIGHT, tx.type)
        assertEquals(LedgerDirection.PAY, tx.direction)
        assertEquals(20.0, tx.equivalent750WeightGrams, 0.001)

        assertEquals(20.0, result.updatedCustomer.goldDebtGrams, 0.001)
        assertEquals(0L, result.updatedCustomer.cashDebtTomans)
    }

