            goldDebtGrams = 0.0,
            cashDebtTomans = 0L
        )

        // Customer sells 2.0g scrap gold at 20,000,000 spot = 40,000,000 Tomans
        val scrapItem = BarterCalculationUseCases.calculateScrapItem(
            title = "طلای کهنه",
            baseKarat = 750,
            karatDeficit = 0,
            grossWeight = 2.0,
            stoneWeight = 0.0,
            spotPrice18k = 20_000_000L,
            deductionPerGram = 0L
        )

        val invoice = BarterInvoice(
            id = "inv-scrap-1",
            invoiceNumber = "1403-301",
