    @Test
    fun testWholesalerWithBullionSettlementDeduction() {
        val customer = Customer(
            id = "c-wholesaler-2",
            name = "همکار بازاری",
            goldDebtGrams = 10.0,
            cashDebtTomans = 0L
        )

        val craftedItem = BarterCalculationUseCases.calculateCraftedItem(
            title = "انگشتر طلا",
            karat = Karat.K18,
            grossWeight = 30.0,
            stoneWeight = 0.0,
            spotPrice18k = 24_000_000L,
            wageType = WageType.PERCENTAGE,
            wageInput = 10.0,
            profitPercent = 7.0,
            taxPercent = 9.0
        )

        val invoice = BarterInvoice(
            id = "inv-102",
            invoiceNumber = "1403-102",
            customer = customer,
            customerRole = CustomerRole.WHOLESALER,
            salesItems = listOf(craftedItem), // 30.0g
            payments = listOf(
                SettlementPaymentItem(
                    method = SettlementMethod.BULLION,
                    goldWeight18k = 18.0,
                    description = "تحویل شمش آبشده",
                    bullionAngNumber = "9912"
                )
            ),
            syncWithLedger = true
        )

        val result = InvoiceLedgerSyncUseCase.generateLedgerSync(invoice, customer)

        // Both the 30g invoice obligation and the 18g bullion receipt are recorded
        assertEquals(2, result.transactionsToCreate.size)
        val invoiceTx = result.transactionsToCreate[0]
        assertEquals(LedgerEntryType.GOLD_WEIGHT, invoiceTx.type)
        assertEquals(LedgerDirection.PAY, invoiceTx.direction)
        assertEquals(30.0, invoiceTx.equivalent750WeightGrams, 0.001)

        val bullionTx = result.transactionsToCreate[1]
        assertEquals(LedgerEntryType.GOLD_WEIGHT, bullionTx.type)
        assertEquals(LedgerDirection.RECEIVE, bullionTx.direction)
        assertEquals(18.0, bullionTx.equivalent750WeightGrams, 0.001)
        assertEquals("9912", bullionTx.angNumber)

        // Net gold debt: 10.0 (initial) + 30.0 (invoice) - 18.0 (bullion) = 22.0g
        assertEquals(22.0, result.updatedCustomer.goldDebtGrams, 0.001)
    }

    @Test
    fun testRetailInvoiceSyncGeneratesCashDebtAndPaymentTransactions() {
        val retailCustomer = Customer(
            id = "c-retail-1",
            name = "مشتری عادی",
            goldDebtGrams = 0.0,
            cashDebtTomans = 0L,
            role = "مشتری عادی"
        )

        val craftedItem = BarterCalculationUseCases.calculateCraftedItem(
            title = "گردنبند طلا",
            karat = Karat.K18,
            grossWeight = 5.0,
            stoneWeight = 0.0,
            spotPrice18k = 20_000_000L,
            wageType = WageType.PERCENTAGE,
            wageInput = 0.0,
            profitPercent = 0.0,
            taxPercent = 0.0
        ) // 5 * 20M = 100,000,000 Tomans

        val invoice = BarterInvoice(
            id = "inv-retail-1",
            invoiceNumber = "1403-201",
            customer = retailCustomer,
            customerRole = CustomerRole.RETAIL,
            salesItems = listOf(craftedItem),
            payments = listOf(
                SettlementPaymentItem(
                    method = SettlementMethod.POS,
                    amountTomans = 70_000_000L,
                    trackingCode = "998877"
                )
            ),
            syncWithLedger = true
        )

        val result = InvoiceLedgerSyncUseCase.generateLedgerSync(invoice, retailCustomer)

        // 1 Invoice charge transaction (100M) + 1 POS payment transaction (70M)
        assertEquals(2, result.transactionsToCreate.size)
        val invoiceTx = result.transactionsToCreate[0]
        assertEquals(LedgerEntryType.CASH_RIAL, invoiceTx.type)
        assertEquals(LedgerDirection.PAY, invoiceTx.direction)
        assertEquals(100_000_000L, invoiceTx.amountTomans)
        assertEquals("inv-retail-1", invoiceTx.invoiceId)
        assertTrue(invoiceTx.isAutoGenerated)

        val paymentTx = result.transactionsToCreate[1]
        assertEquals(LedgerEntryType.CASH_RIAL, paymentTx.type)
        assertEquals(LedgerDirection.RECEIVE, paymentTx.direction)
        assertEquals(70_000_000L, paymentTx.amountTomans)
        assertEquals("998877", paymentTx.trackingCode)
        assertEquals("تسویه کارتخوان", paymentTx.tagBadge)
        assertEquals("inv-retail-1", paymentTx.invoiceId)

        // Net debt: 100M - 70M = 30M Tomans
        assertEquals(0.0, result.updatedCustomer.goldDebtGrams, 0.0001)
        assertEquals(30_000_000L, result.updatedCustomer.cashDebtTomans)
    }

