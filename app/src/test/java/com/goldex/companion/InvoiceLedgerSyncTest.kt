            syncWithLedger = true
        )

        val result = InvoiceLedgerSyncUseCase.generateLedgerSync(invoice, customer)

        assertEquals(2, result.transactionsToCreate.size)
        // 1. Scrap purchase credit transaction (shop received gold -> customer is credited)
        val purchaseTx = result.transactionsToCreate[0]
        assertEquals(LedgerEntryType.CASH_RIAL, purchaseTx.type)
        assertEquals(LedgerDirection.RECEIVE, purchaseTx.direction)
