        val paymentTx = result.transactionsToCreate[1]
        assertEquals(LedgerEntryType.CASH_RIAL, paymentTx.type)
        assertEquals(LedgerDirection.PAY, paymentTx.direction)
        assertEquals(40_000_000L, paymentTx.amountTomans)
        assertEquals("تسویه خرید طلا", paymentTx.tagBadge)

        // Balances out to 0
        assertEquals(0L, result.updatedCustomer.cashDebtTomans)
    }

