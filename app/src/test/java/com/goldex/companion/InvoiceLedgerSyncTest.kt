    @Test
    fun testReverseLedgerSyncRestoresCustomerBalance() {
        val original = Customer(id = "c1", name = "تست", goldDebtGrams = 10.0, cashDebtTomans = 50_000_000L)

        val goldTx = LedgerTransaction(
            type = LedgerEntryType.GOLD_WEIGHT,
            direction = LedgerDirection.PAY,
            equivalent750WeightGrams = 8.0,
            customerId = "c1"
        )
        val cashTx = LedgerTransaction(
            type = LedgerEntryType.CASH_RIAL,
            direction = LedgerDirection.PAY,
            amountTomans = 20_000_000L,
            customerId = "c1"
        )

        val modified = original.copy(
            goldDebtGrams = original.goldDebtGrams + 8.0,
            cashDebtTomans = original.cashDebtTomans + 20_000_000L
        )
        assertEquals(18.0, modified.goldDebtGrams, 0.001)
        assertEquals(70_000_000L, modified.cashDebtTomans)

        val restored = InvoiceLedgerSyncUseCase.reverseLedgerSync(listOf(goldTx, cashTx), modified)
        assertEquals(10.0, restored.goldDebtGrams, 0.001)
        assertEquals(50_000_000L, restored.cashDebtTomans)
    }

    @Test
    fun testLedgerTransactionWithInvoiceLinkRoundTrip() {
        val tx = LedgerTransaction(
            id = "tx-auto-1",
            customerId = "c-100",
            documentNumber = "IR-1403-999",
            title = "فاکتور تهاتر طلا",
            dateTime = "۱۴۰۳/۰۶/۲۵ ۱۰:۰۰",
            type = LedgerEntryType.GOLD_WEIGHT,
            direction = LedgerDirection.PAY,
            equivalent750WeightGrams = 14.500,
            invoiceId = "inv-target-1",
            invoiceNumber = "IR-1403-999",
            isAutoGenerated = true
        )

        val json = PersistenceJsonCodecs.encodeLedgerTransactions(listOf(tx))
        val decoded = PersistenceJsonCodecs.decodeLedgerTransactions(json).single()

        assertEquals("tx-auto-1", decoded.id)
        assertEquals("c-100", decoded.customerId)
        assertEquals("inv-target-1", decoded.invoiceId)
        assertEquals("IR-1403-999", decoded.invoiceNumber)
        assertTrue(decoded.isAutoGenerated)
        assertEquals(14.500, decoded.equivalent750WeightGrams, 0.001)
    }

    @Test
    fun testBarterInvoiceSerializationRoundTrip() {
        val invoice = BarterInvoice(
            id = "inv-full-1",
            invoiceNumber = "IR-1404-555",
            createdAt = 1715000000000L,
            customer = Customer(id = "c55", name = "جواد زرگر", phone = "09123334455"),
            customerRole = CustomerRole.WHOLESALER,
            spotPrice18k = 24_500_000L,
            salesItems = listOf(
                CraftedGoldItem(
                    id = "item-1",
                    title = "سرویس طلا",
                    karat = Karat.K18,
                    customKaratValue = 750,
                    grossWeight = 12.0,
                    stoneWeight = 0.0,
                    netWeight = 12.0,
                    spotPrice = 24_500_000L,
                    wageType = WageType.PERCENTAGE,
                    wageInput = 8.0,
                    wageAmount = 23_520_000.0,
                    profitPercent = 7.0,
                    profitAmount = 22_241_440.0,
                    taxPercent = 9.0,
                    taxAmount = 4_118_529.6,
                    rawGoldValue = 294_000_000.0,
                    totalPayable = 343_879_969.6,
                    equivalent18kWeight = 12.0
                )
            ),
            payments = listOf(
                SettlementPaymentItem(
                    id = "pay-1",
                    method = SettlementMethod.POS,
                    amountTomans = 200_000_000L,
                    trackingCode = "POS-7788"
                )
            ),
            syncWithLedger = true,
            note = "تحویل فوری در سرای امید"
        )

        val json = PersistenceJsonCodecs.encodeBarterInvoices(listOf(invoice))
        val decodedList = PersistenceJsonCodecs.decodeBarterInvoices(json)

        assertEquals(1, decodedList.size)
        val decoded = decodedList.single()

        assertEquals("inv-full-1", decoded.id)
        assertEquals("IR-1404-555", decoded.invoiceNumber)
        assertEquals("جواد زرگر", decoded.customer?.name)
        assertEquals(CustomerRole.WHOLESALER, decoded.customerRole)
        assertEquals(24_500_000L, decoded.spotPrice18k)
        assertEquals(1, decoded.salesItems.size)
        assertEquals("سرویس طلا", decoded.salesItems.first().title)
        assertEquals(1, decoded.payments.size)
        assertEquals(200_000_000L, decoded.payments.first().amountTomans)
        assertTrue(decoded.syncWithLedger)
        assertEquals("تحویل فوری در سرای امید", decoded.note)
        assertEquals("1404-555", decoded.cleanInvoiceNumber)
    }

    @Test
    fun testCleanInvoiceNumberAndCleanDocumentNumberRemovesIRPrefix() {
        val legacyInvoice = BarterInvoice(
            invoiceNumber = "IR-1403-888"
        )
        assertEquals("1403-888", legacyInvoice.cleanInvoiceNumber)

        val legacyTx = LedgerTransaction(
            customerId = "c1",
            documentNumber = "IR-8842",
            invoiceNumber = "IR-1403-777"
        )
        assertEquals("8842", legacyTx.cleanDocumentNumber)
        assertEquals("1403-777", legacyTx.cleanInvoiceNumber)

        val modernInvoice = BarterInvoice(
            invoiceNumber = "1403-999"
        )
        assertEquals("1403-999", modernInvoice.cleanInvoiceNumber)
    }
