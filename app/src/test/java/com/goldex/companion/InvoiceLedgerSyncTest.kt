    @Test
    fun testReversalRoundTripRestoresOriginalCustomerBalanceForMultiPaymentInvoice() {
        val initialCustomer = Customer(
            id = "c-rev-1",
            name = "مشتری آزمون لغو",
            goldDebtGrams = 12.5,
            cashDebtTomans = 45_000_000L
        )

        val craftedItem = BarterCalculationUseCases.calculateCraftedItem(
            title = "دستبند",
            karat = Karat.K18,
            grossWeight = 10.0,
            stoneWeight = 0.0,
            spotPrice18k = 25_000_000L,
            wageType = WageType.PERCENTAGE,
            wageInput = 10.0,
            profitPercent = 5.0,
            taxPercent = 9.0
        )

        val invoice = BarterInvoice(
            id = "inv-rev",
            customer = initialCustomer,
            customerRole = CustomerRole.RETAIL,
            salesItems = listOf(craftedItem),
            payments = listOf(
                SettlementPaymentItem(
                    method = SettlementMethod.POS,
                    amountTomans = 150_000_000L
                ),
                SettlementPaymentItem(
                    method = SettlementMethod.TRANSFER,
                    amountTomans = 50_000_000L
                )
            ),
            syncWithLedger = true
        )

        val syncResult = InvoiceLedgerSyncUseCase.generateLedgerSync(invoice, initialCustomer)
        assertTrue(syncResult.transactionsToCreate.size >= 2)
        assertNotEquals(initialCustomer.cashDebtTomans, syncResult.updatedCustomer.cashDebtTomans)

        // Now reverse
        val restoredCustomer = InvoiceLedgerSyncUseCase.reverseLedgerSync(
            syncResult.transactionsToCreate,
            syncResult.updatedCustomer
        )

        assertEquals(initialCustomer.goldDebtGrams, restoredCustomer.goldDebtGrams, 0.0001)
        assertEquals(initialCustomer.cashDebtTomans, restoredCustomer.cashDebtTomans)
    }

